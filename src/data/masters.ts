function history(purchase: number, selling: number, drift: number[]): RatePoint[] {
  return months.map((date, i) => {
    const d = drift[i] ?? 0;
    return {
      date,
      purchaseRate: Math.round(purchase * (1 + d)),
      sellingRate: Math.round(selling * (1 + d * 0.8)),
    };
  });
}

