const uuid = (key: string) => {
  const h = createHash("md5").update(`meridian-seed:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const s = (v: string | null | undefined) =>
  v === null || v === undefined || v === "" ? "null" : `'${v.replaceAll("'", "''")}'`;
const n = (v: number | null | undefined) =>
  v === null || v === undefined || Number.isNaN(v) ? "null" : String(v);
const B = "(select business_id from _seed)";
const snake = (v: string) =>
  v
    .toLowerCase()
    .replaceAll(" / ", "_or_")
    .replaceAll(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");
const UNIT: Record<string, string> = {
  MT: "MT",
  Brass: "BRASS",
  Trips: "TRIP",
  CFT: "CFT",
  "m³": "CUM",
};
const MODE: Record<string, string> = {
  UPI: "upi",
  "Bank Transfer": "bank_transfer",
  Cheque: "cheque",
  Cash: "cash",
};

const out: string[] = [];
const w = (line: string) => out.push(line);
const insert = (table: string, cols: string[], rows: (string | number)[][]) => {
  if (!rows.length) return;
  w(`insert into public.${table} (${cols.join(", ")}) values`);
  rows.forEach((r, i) => w(`  (${r.join(", ")})${i === rows.length - 1 ? "" : ","}`));
  w("on conflict (id) do nothing;\n");
};

